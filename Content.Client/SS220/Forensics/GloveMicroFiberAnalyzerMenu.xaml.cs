/// <summary>
/// Shows analysis progress and the analyzer's stored glove samples, images and descriptions.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class GloveMicroFiberAnalyzerMenu : DefaultWindow
{
    [Dependency] private readonly IPrototypeManager _prototype = default!;
    [Dependency] private readonly IGameTiming _timing = default!;

    private bool _hasSample;
    private TimeSpan _printReadyAt;
    private GloveMicroFiberAnalyzerResultsMessage? _results;
    private readonly Dictionary<int, Button> _historyButtons = [];
    private bool _descriptionLoaded;
    private bool _descriptionDirty;
    private string _descriptionSource = string.Empty;
    private bool _analysisInterrupted;

    /// <summary>
    /// The stored sample currently displayed, or null when viewing the physical swab.
    /// </summary>
    public int? SelectedSampleId { get; private set; }

    /// <summary>
    /// The physical swab targeted by actions on the pending sample.
    /// </summary>
    public NetEntity? PendingSwab => _results?.PendingSwab;

    public GloveMicroFiberAnalyzerMenu()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);
        AnalyzerNumberLabel.Text = Loc.GetString("glove-micro-fiber-analyzer-interface-number", ("number", "—"));
        CurrentSample.ModulateSelfOverride = GloveMicroFiberAnalyzerColors.Accent;
        UpdatePrinterConnection();
        CurrentSample.OnPressed += _ => SelectSample(null);
        DescriptionEdit.IsValid = text => text.Length <= GloveMicroFiberAnalyzerUi.MaxDescriptionLength;
        DescriptionEdit.OnTextChanged += _ =>
        {
            _descriptionDirty = DescriptionEdit.Text != _descriptionSource;
            UpdateDescriptionState();
        };
        InitializeComparison();
    }

    /// <summary>
    /// Updates physical analysis and history while preserving edits to the selected description.
    /// </summary>
    public void UpdateResults(GloveMicroFiberAnalyzerResultsMessage state)
    {
        var previous = _results;
        var previousSelection = SelectedSampleId;
        UpdateAnalysisInterruption(previous, state);
        SelectLatestCompletedSample(previous, state);

        Eject.Disabled = !state.HasSwab;
        Eject.Visible = state.HasSwab;
        _results = state;
        AnalyzerNumberLabel.Text = Loc.GetString("glove-micro-fiber-analyzer-interface-number",
            ("number", state.AnalyzerId));
        AnalyzerNumberLabel.ToolTip = Loc.GetString("glove-micro-fiber-analyzer-interface-number-tooltip",
            ("number", state.AnalyzerId));
        UpdatePrinterConnection();
        _printReadyAt = state.PrintReadyAt;
        UpdateHistory(state.History);
        var resetDescription = ShouldResetDescription(previousSelection, previous, state);
        RefreshResults(resetDescription: resetDescription);
    }

    private bool ShouldResetDescription(
        int? previousSelection,
        GloveMicroFiberAnalyzerResultsMessage? previous,
        GloveMicroFiberAnalyzerResultsMessage current)
    {
        var pendingChanged = HasPendingSampleChanged(previous, current);
        if (previousSelection != SelectedSampleId)
            return true;

        return pendingChanged;
    }

    private bool HasPendingSampleChanged(
        GloveMicroFiberAnalyzerResultsMessage? previous,
        GloveMicroFiberAnalyzerResultsMessage current)
    {
        if (SelectedSampleId != null)
            return false;

        if (previous == null)
            return false;

        return previous.PendingSwab != current.PendingSwab;
    }

    private void UpdateAnalysisInterruption(GloveMicroFiberAnalyzerResultsMessage? previous,
        GloveMicroFiberAnalyzerResultsMessage current)
    {
        if (current.IsAnalyzing)
        {
            _analysisInterrupted = false;
            return;
        }

        if (previous == null)
            return;

        if (previous.IsAnalyzing)
            _analysisInterrupted = current.History.Count <= previous.History.Count;

        if (!current.HasSwab)
            return;

        if (previous.PendingSwab != current.PendingSwab)
            _analysisInterrupted = false;
    }

    private void SelectLatestCompletedSample(GloveMicroFiberAnalyzerResultsMessage? previous,
        GloveMicroFiberAnalyzerResultsMessage current)
    {
        if (!ShouldSelectLatestCompletedSample(previous, current))
            return;

        SelectedSampleId = current.History[^1].Id;
    }

    private bool ShouldSelectLatestCompletedSample(
        GloveMicroFiberAnalyzerResultsMessage? previous,
        GloveMicroFiberAnalyzerResultsMessage current)
    {
        if (SelectedSampleId != null)
            return false;

        if (current.History.Count == 0)
            return false;

        if (previous == null)
            return !current.HasSwab;

        if (current.History.Count <= previous.History.Count)
            return false;

        return true;
    }

    private void UpdateHistory(List<GloveMicroFiberAnalyzerHistoryEntry> history)
    {
        HistoryEntries.RemoveAllChildren();
        _historyButtons.Clear();
        HistoryEmpty.Visible = history.Count == 0;
        HistoryCount.Text = history.Count.ToString(CultureInfo.InvariantCulture);
        for (var i = history.Count - 1; i >= 0; i--)
        {
            var sample = history[i];
            var button = new HistorySampleButton
            {
                Text = GetSampleName(sample),
                ClipText = true,
                ToolTip = sample.Identifier,
                ToggleMode = true,
                HorizontalExpand = true,
            };
            button.OnPressed += _ => SelectSample(sample.Id);
            _historyButtons.Add(sample.Id, button);
            HistoryEntries.AddChild(button);
        }

        UpdateComparisonHistory(history);
    }

    private void SelectSample(int? id)
    {
        CompareHistory.Pressed = false;
        var changed = SelectedSampleId != id;
        SelectedSampleId = id;
        RefreshResults(resetDescription: changed);
    }

    private void RefreshResults(bool resetDescription = false)
    {
        TracesContainer.RemoveAllChildren();
        StorageMicroFibersContainer.RemoveAllChildren();
        if (_results == null)
            return;

        var stored = FindSelectedHistoryEntry(_results.History);
        var missingSelection = SelectedSampleId != null && stored == null;
        if (missingSelection)
            SelectedSampleId = null;

        UpdateSampleSelection(_results);
        UpdateSampleHeader(_results, stored);
        UpdateSampleControls(_results, stored);
        UpdateDescription(stored?.Description ?? _results.PendingDescription, reset: resetDescription || missingSelection);
        UpdatePrinterState();
        UpdateAnalysisProgress();
        UpdateComparisonView();
        DisplaySampleResults(_results, stored);
    }

    private GloveMicroFiberAnalyzerHistoryEntry? FindSelectedHistoryEntry(
        List<GloveMicroFiberAnalyzerHistoryEntry> history)
    {
        if (SelectedSampleId == null)
            return null;

        return history.Find(sample => sample.Id == SelectedSampleId.Value);
    }

    private void UpdateSampleSelection(GloveMicroFiberAnalyzerResultsMessage state)
    {
        PendingSamplePanel.Visible = state.HasSwab;
        CurrentSample.Pressed = !CompareHistory.Pressed && SelectedSampleId == null;
        CurrentSample.ModulateSelfOverride = CurrentSample.Pressed
            ? GloveMicroFiberAnalyzerColors.Accent
            : Palettes.Cyan.Base;
        foreach (var (id, button) in _historyButtons)
        {
            button.Pressed = !CompareHistory.Pressed && SelectedSampleId == id;
        }
    }

    private void UpdateSampleHeader(GloveMicroFiberAnalyzerResultsMessage state,
        GloveMicroFiberAnalyzerHistoryEntry? stored)
    {
        SelectedSampleLabel.Text = stored == null
            ? Loc.GetString("glove-micro-fiber-analyzer-interface-current-sample")
            : GetSampleName(stored);
        SelectedSampleLabel.ToolTip = SelectedSampleLabel.Text;
        SelectedSampleLabel.Visible = ShouldShowSampleHeader(state, stored);
        var sourceName = stored?.SourceName ?? state.PendingSourceName;
        SampleSourceLabel.Visible = !CompareHistory.Pressed && !string.IsNullOrEmpty(sourceName);
        SampleSourceLabel.Text = Loc.GetString("glove-micro-fiber-analyzer-interface-source-heading",
            ("source", sourceName));
        SampleSourceLabel.ToolTip = SampleSourceLabel.Text;
        AnalysisTimeLabel.Visible = !CompareHistory.Pressed && stored != null;
        AnalysisTimeLabel.Text = stored == null ? string.Empty : GetAnalysisTimeText(stored);
        AnalysisTimeLabel.ToolTip = AnalysisTimeLabel.Text;
    }

    private bool ShouldShowSampleHeader(
        GloveMicroFiberAnalyzerResultsMessage state,
        GloveMicroFiberAnalyzerHistoryEntry? stored)
    {
        if (CompareHistory.Pressed)
            return false;

        if (stored != null)
            return true;

        return state.HasSwab;
    }

    private void UpdateSampleControls(GloveMicroFiberAnalyzerResultsMessage state,
        GloveMicroFiberAnalyzerHistoryEntry? stored)
    {
        _hasSample = stored != null;
        ResultsDetails.Visible = !CompareHistory.Pressed && stored != null;
        DescriptionPanel.Visible = ResultsDetails.Visible;
        StatusLabel.Visible = !CompareHistory.Pressed && stored == null;
        NoTraces.Visible = HasNoGloveTraces(stored);
        GloveSamplesCount.Text = (stored?.GloveMicroFibers.Count ?? 0).ToString(CultureInfo.InvariantCulture);
        StorageMicroFiberSamplesCount.Text = (stored?.StorageMicroFibers.Count ?? 0)
            .ToString(CultureInfo.InvariantCulture);
        Analyze.Visible = !CompareHistory.Pressed && stored == null;
        Analyze.Disabled = !CanAnalyzeSample(state, stored);
    }

    private static bool HasNoGloveTraces(GloveMicroFiberAnalyzerHistoryEntry? stored)
    {
        if (stored == null)
            return false;

        return stored.GloveMicroFibers.Count == 0;
    }

    private static bool CanAnalyzeSample(
        GloveMicroFiberAnalyzerResultsMessage state,
        GloveMicroFiberAnalyzerHistoryEntry? stored)
    {
        if (stored != null)
            return false;

        if (!state.HasSwab)
            return false;

        if (!state.Used)
            return false;

        if (state.IsAnalyzing)
            return false;

        return true;
    }

    private void DisplaySampleResults(GloveMicroFiberAnalyzerResultsMessage state,
        GloveMicroFiberAnalyzerHistoryEntry? stored)
    {
        if (stored == null)
        {
            UpdatePendingSampleStatus(state);
            return;
        }

        StatusLabel.Text = string.Empty;
        DisplayTraces(stored.GloveMicroFibers);
        DisplayStorageMicroFibers(StorageMicroFibersContainer, stored.StorageMicroFibers,
            "glove-micro-fiber-analyzer-interface-empty-category");
    }

    private void UpdatePendingSampleStatus(GloveMicroFiberAnalyzerResultsMessage state)
    {
        if (state.IsAnalyzing)
        {
            StatusLabel.Text = Loc.GetString("glove-micro-fiber-analyzer-interface-analyzing");
            return;
        }

        if (_analysisInterrupted)
        {
            StatusLabel.Text = Loc.GetString("glove-micro-fiber-analyzer-interface-analysis-interrupted");
            return;
        }

        if (!state.HasSwab)
        {
            StatusLabel.Text = Loc.GetString("glove-micro-fiber-analyzer-interface-no-swab");
            return;
        }

        if (!state.Used)
        {
            StatusLabel.Text = Loc.GetString("glove-micro-fiber-analyzer-interface-unused-swab");
            return;
        }

        StatusLabel.Text = Loc.GetString("glove-micro-fiber-analyzer-interface-ready");
    }

    private void UpdateDescription(string description, bool reset)
    {
        if (ShouldReloadDescription(description, reset))
        {
            DescriptionEdit.Text = description;
            _descriptionDirty = false;
        }

        _descriptionLoaded = true;
        _descriptionSource = description;
        UpdateDescriptionState();
    }

    private bool ShouldReloadDescription(string description, bool reset)
    {
        if (reset)
            return true;

        if (!_descriptionLoaded)
            return true;

        if (!_descriptionDirty)
            return true;

        return DescriptionEdit.Text == description;
    }

    private void UpdateDescriptionState()
    {
        var editable = CanEditDescription();
        DescriptionEdit.Editable = editable;
        SaveDescription.Disabled = !editable || !_descriptionDirty;
    }

    private bool CanEditDescription()
    {
        if (CompareHistory.Pressed)
            return false;

        if (_results == null)
            return false;

        return SelectedSampleId != null;
    }

    private void DisplayTraces(List<GloveMicroFiberTrace> traces)
    {
        for (var i = 0; i < traces.Count; i++)
        {
            var trace = traces[i];
            TracesContainer.AddChild(CreateSampleCard(trace.Code, trace.Prototype,
                "glove-micro-fiber-analyzer-interface-glove-sample-number", i + 1,
                "glove-micro-fiber-analyzer-interface-unknown-type"));
        }
    }

    private PanelContainer CreateSampleCard(string code, EntProtoId? prototypeId, string sampleNumberKey, int number,
        string unknownTypeKey, string sourceName = "")
    {
        var card = new PanelContainer
        {
            HorizontalExpand = true,
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = GloveMicroFiberAnalyzerColors.PanelBackground,
                BorderColor = GloveMicroFiberAnalyzerColors.AccentBorder,
                BorderThickness = new Thickness(3, 1, 1, 1),
            },
        };
        var contents = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            SeparationOverride = 8,
            Margin = new Thickness(8),
        };
        card.AddChild(contents);
        var heading = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            SeparationOverride = 10,
        };
        contents.AddChild(heading);
        var itemName = string.IsNullOrEmpty(sourceName) ? Loc.GetString(unknownTypeKey) : sourceName;
        if (_prototype.TryIndex(prototypeId, out var prototype))
            itemName = AddSampleAppearance(heading, prototype, sourceName);

        var names = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            VerticalAlignment = VAlignment.Center,
            SeparationOverride = 3,
        };
        heading.AddChild(names);
        names.AddChild(new Label
        {
            Text = Loc.GetString(sampleNumberKey, ("number", number)),
            StyleClasses = { StyleClass.LabelSubText },
            FontColorOverride = GloveMicroFiberAnalyzerColors.MutedText,
        });
        var name = new RichTextLabel { HorizontalExpand = true };
        name.SetMessage(FormattedMessage.FromUnformatted(itemName), GloveMicroFiberAnalyzerColors.Text);
        names.AddChild(name);
        var codePanel = new PanelContainer
        {
            HorizontalExpand = true,
            PanelOverride = new StyleBoxFlat(GloveMicroFiberAnalyzerColors.InsetBackground),
        };
        var codeLabel = new RichTextLabel
        {
            HorizontalExpand = true,
            StyleClasses = { StyleClass.Monospace },
            Margin = new Thickness(8, 6),
            MouseFilter = MouseFilterMode.Stop,
            ToolTip = code,
        };
        codeLabel.SetMessage(FormattedMessage.FromUnformatted(FormatSampleCode(code)),
            GloveMicroFiberAnalyzerColors.CodeText);
        codePanel.AddChild(codeLabel);
        contents.AddChild(codePanel);
        return card;
    }

    private string AddSampleAppearance(BoxContainer heading, EntityPrototype prototype, string sourceName)
    {
        var itemName = sourceName;
        if (string.IsNullOrEmpty(sourceName))
            itemName = prototype.Name;

        var image = new EntityPrototypeView
        {
            MinSize = new Vector2(64, 64),
            MaxSize = new Vector2(64, 64),
            Stretch = SpriteView.StretchMode.Fill,
            VerticalAlignment = VAlignment.Center,
            MouseFilter = MouseFilterMode.Ignore,
        };
        image.SetPrototype(prototype.ID);
        heading.AddChild(image);
        return itemName;
    }

    private static string FormatSampleCode(string code)
    {
        const int CodeLength = 32;
        const int GroupLength = 4;

        if (code.Length != CodeLength)
            return code;

        if (!code.All(char.IsAsciiHexDigit))
            return code;

        var groups = new string[code.Length / GroupLength];
        for (var i = 0; i < groups.Length; i++)
        {
            groups[i] = code.Substring(i * GroupLength, GroupLength);
        }

        return string.Join(" ", groups);
    }

    private void DisplayStorageMicroFibers(BoxContainer container, List<StorageMicroFiberTrace> storageMicroFibers,
        string emptyKey)
    {
        if (storageMicroFibers.Count == 0)
        {
            var empty = new RichTextLabel { HorizontalExpand = true };
            empty.SetMessage(FormattedMessage.FromUnformatted(Loc.GetString(emptyKey)),
                GloveMicroFiberAnalyzerColors.MutedText);
            container.AddChild(empty);
            return;
        }

        for (var i = 0; i < storageMicroFibers.Count; i++)
        {
            var fiber = storageMicroFibers[i];
            container.AddChild(CreateSampleCard(fiber.Code, fiber.Prototype,
                "glove-micro-fiber-analyzer-interface-storage-sample-number", i + 1,
                "glove-micro-fiber-analyzer-interface-unknown-item", fiber.SourceName));
        }
    }

    private string GetSampleName(GloveMicroFiberAnalyzerHistoryEntry sample)
    {
        return Loc.GetString("glove-micro-fiber-analyzer-interface-history-sample", ("identifier", sample.Identifier));
    }

    private string GetAnalysisTimeText(GloveMicroFiberAnalyzerHistoryEntry sample)
    {
        return Loc.GetString("glove-micro-fiber-analyzer-interface-analyzed-at",
            ("time", GloveMicroFiberAnalyzerUi.FormatRoundTime(sample.AnalyzedAt)));
    }

    /// <summary>
    /// Prevents repeated clicks while the server processes a print request.
    /// </summary>
    public void StartPrintCooldown()
    {
        _printReadyAt = _timing.CurTime + (_results?.PrintCooldown ?? TimeSpan.Zero);
        UpdatePrinterState();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        UpdatePrinterState();
        UpdateAnalysisProgress();
    }

    private void UpdatePrinterState()
    {
        PrinterButton.Disabled = !CanPrintReport();
    }

    private bool CanPrintReport()
    {
        if (_results == null)
            return false;

        var hasReport = CompareHistory.Pressed ? _comparisonHasResult : _hasSample;
        if (!hasReport)
            return false;

        if (_results.PrinterStatus != GloveMicroFiberAnalyzerPrinterStatus.Ready)
            return false;

        if (_timing.CurTime < _printReadyAt)
            return false;

        return true;
    }

    private void UpdatePrinterConnection()
    {
        var status = _results?.PrinterStatus ?? GloveMicroFiberAnalyzerPrinterStatus.Disconnected;
        PrinterStatusIcon.ModulateSelfOverride = status == GloveMicroFiberAnalyzerPrinterStatus.Disconnected
            ? Palettes.Red.Base
            : Palettes.Green.Base;
        var tooltip = status switch
        {
            GloveMicroFiberAnalyzerPrinterStatus.Ready => "glove-micro-fiber-analyzer-interface-printer-ready",
            GloveMicroFiberAnalyzerPrinterStatus.Unavailable =>
                "glove-micro-fiber-analyzer-interface-printer-unavailable",
            _ => "glove-micro-fiber-analyzer-interface-printer-disconnected",
        };
        PrinterStatusIcon.ToolTip = Loc.GetString(tooltip);
        PrinterButton.ToolTip = PrinterStatusIcon.ToolTip;
    }

    private void UpdateAnalysisProgress()
    {
        AnalysisProgress.Visible = ShouldShowAnalysisProgress();
        if (!AnalysisProgress.Visible || _results == null)
        {
            AnalysisProgress.Value = 0;
            return;
        }

        var duration = (_results.AnalysisFinishAt - _results.AnalysisStartedAt).TotalSeconds;
        if (duration <= 0)
        {
            AnalysisProgress.Value = 1;
            return;
        }

        var elapsed = (_timing.CurTime - _results.AnalysisStartedAt).TotalSeconds;
        AnalysisProgress.Value = (float)Math.Clamp(elapsed / duration, 0, 1);
    }

    private bool ShouldShowAnalysisProgress()
    {
        if (CompareHistory.Pressed)
            return false;

        if (SelectedSampleId != null)
            return false;

        if (_results == null)
            return false;

        return _results.IsAnalyzing;
    }

    private sealed class HistorySampleButton : Button
    {
        public HistorySampleButton()
        {
            ModulateSelfOverride = Color.White;
            TextAlign = Label.AlignMode.Left;
            MinHeight = 36;
            StyleBoxOverride = new StyleBoxFlat
            {
                ContentMarginLeftOverride = 8,
                ContentMarginTopOverride = 6,
                ContentMarginRightOverride = 8,
                ContentMarginBottomOverride = 6,
            };
            UpdateStyleBox();
        }

        protected override void DrawModeChanged()
        {
            base.DrawModeChanged();
            UpdateStyleBox();
        }

        private void UpdateStyleBox()
        {
            if (StyleBoxOverride is not StyleBoxFlat style)
                return;

            style.BackgroundColor = DrawMode switch
            {
                DrawModeEnum.Pressed => Palettes.Green.PressedElement,
                DrawModeEnum.Hover => Palettes.Slate.HoveredElement,
                DrawModeEnum.Disabled => Palettes.Slate.DisabledElement,
                _ => Palettes.Slate.Element,
            };
            style.BorderColor = Pressed ? Palettes.Green.Base : GloveMicroFiberAnalyzerColors.Border;
            style.BorderThickness = new Thickness(Pressed ? 3 : 1, 1, 1, 1);
        }
    }
}

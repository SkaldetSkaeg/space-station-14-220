using System.Text;
using Content.Shared.SS220.Forensics;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.SS220.Forensics;

/// <summary>
/// Shows the scanned glove traces, reference sample and comparison result.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class GlovePrintScannerMenu : DefaultWindow
{
    public GlovePrintScannerMenu()
    {
        RobustXamlLoader.Load(this);
    }

    /// <summary>
    /// Displays the results received through the private interface message.
    /// </summary>
    public void UpdateResults(GlovePrintScannerResultsMessage state)
    {
        Clear.Disabled = state.Sample == null && state.LastScannedName.Length == 0;
        TargetLabel.Text = state.LastScannedName.Length == 0
            ? Loc.GetString("glove-print-scanner-interface-no-target")
            : Loc.GetString("glove-print-scanner-interface-target", ("target", state.LastScannedName));
        SampleLabel.Text = state.Sample == null
            ? Loc.GetString("glove-print-scanner-interface-no-sample")
            : Loc.GetString("glove-print-scanner-interface-sample", ("sample", state.Sample));

        MatchLabel.Text = string.Empty;
        if (state.Sample != null && state.LastScannedName.Length > 0)
        {
            MatchLabel.Text = Loc.GetString(state.GlovePrints.Contains(state.Sample)
                ? "glove-print-scanner-interface-match"
                : "glove-print-scanner-interface-no-match");
        }

        if (state.GlovePrints.Count == 0)
        {
            TracesLabel.Text = Loc.GetString("glove-print-scanner-interface-no-traces");
            return;
        }

        var text = new StringBuilder();
        foreach (var print in state.GlovePrints)
        {
            text.AppendLine(print);
        }

        TracesLabel.Text = text.ToString();
    }
}

using System.Text;
using Content.Shared.SS220.Forensics;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client.SS220.Forensics;

/// <summary>
/// Shows the collected glove types and pair codes from the inserted sample.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class GlovePrintAnalyzerMenu : DefaultWindow
{
    [Dependency] private readonly IPrototypeManager _prototype = default!;

    public GlovePrintAnalyzerMenu()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);
    }

    /// <summary>
    /// Displays the current physical sample's results without interpreting source names as markup.
    /// </summary>
    public void UpdateResults(GlovePrintAnalyzerResultsMessage state)
    {
        Eject.Disabled = !state.HasSwab;
        SourceLabel.SetMessage(string.Empty);
        TracesLabel.SetMessage(string.Empty);

        if (!state.HasSwab)
        {
            StatusLabel.Text = Loc.GetString("glove-print-analyzer-interface-no-swab");
            return;
        }

        if (state.SourceName == null)
        {
            StatusLabel.Text = Loc.GetString("glove-print-analyzer-interface-unused-swab");
            return;
        }

        SourceLabel.SetMessage(Loc.GetString("glove-print-analyzer-interface-source", ("source", state.SourceName)));
        if (state.GlovePrints.Count == 0)
        {
            StatusLabel.Text = Loc.GetString("glove-print-analyzer-interface-no-traces");
            return;
        }

        StatusLabel.Text = Loc.GetString("glove-print-analyzer-interface-results");
        var text = new StringBuilder();
        foreach (var trace in state.GlovePrints)
        {
            text.AppendLine(Loc.GetString("glove-print-analyzer-interface-type", ("type", GetGloveName(trace))));
            text.AppendLine(Loc.GetString("glove-print-analyzer-interface-code", ("code", trace.Code)));
            text.AppendLine();
        }

        TracesLabel.SetMessage(text.ToString());
    }

    private string GetGloveName(GlovePrintTrace trace)
    {
        if (!_prototype.TryIndex(trace.Prototype, out var prototype))
            return Loc.GetString("glove-print-analyzer-interface-unknown-type");

        return prototype.Name;
    }
}

/// <summary>
/// Shows analysis progress and the analyzer's stored glove samples, images and descriptions.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class GlovePrintAnalyzerMenu : DefaultWindow
{
    [Dependency] private readonly IPrototypeManager _prototype = default!;
    [Dependency] private readonly IGameTiming _timing = default!;

    private bool _hasSample;
    private TimeSpan _printReadyAt;
    private TimeSpan _printCooldown;
    private GlovePrintAnalyzerResultsMessage? _results;
    private readonly Dictionary<int, Button> _historyButtons = [];
    private bool _descriptionLoaded;
    private bool _descriptionDirty;
    private string _descriptionSource = string.Empty;
    private bool _analysisInterrupted;

    /// <summary>
    /// The stored sample currently displayed, or null when viewing the physical swab.
    /// </summary>
    public int? SelectedSampleId { get; private set; }

    /// <summary>
    /// The physical swab targeted by actions on the pending sample.
    /// </summary>
    public NetEntity? PendingSwab => _results?.PendingSwab;

    public GlovePrintAnalyzerMenu()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);
        AnalyzerNumberLabel.Text = Loc.GetString("glove-print-analyzer-interface-number", ("number", "—"));
        CurrentSample.ModulateSelfOverride = Color.FromHex("#48AFCE");
        UpdatePrinterConnection();
        CurrentSample.OnPressed += _ => SelectSample(null);
        DescriptionEdit.IsValid = text => text.Length <= GlovePrintAnalyzerUi.MaxDescriptionLength;
        DescriptionEdit.OnTextChanged += _ =>
        {
            _descriptionDirty = DescriptionEdit.Text != _descriptionSource;
            UpdateDescriptionState();
        };
        InitializeComparison();
    }

    /// <summary>
    /// Updates physical analysis and history while preserving edits to the selected description.
    /// </summary>
    public void UpdateResults(GlovePrintAnalyzerResultsMessage state)
    {
        var previous = _results;
        var previousSelection = SelectedSampleId;
        if (previous != null && previous.IsAnalyzing && !state.IsAnalyzing)
            _analysisInterrupted = state.History.Count <= previous.History.Count;

        if (state.IsAnalyzing || (previous != null && previous.PendingSwab != state.PendingSwab && state.HasSwab))
            _analysisInterrupted = false;

        var historyAdded = previous != null && state.History.Count > previous.History.Count;
        if (SelectedSampleId == null && state.History.Count > 0 &&
            (historyAdded || previous == null && !state.HasSwab))
            SelectedSampleId = state.History[^1].Id;

        Eject.Disabled = !state.HasSwab;
        _results = state;
        AnalyzerNumberLabel.Text = Loc.GetString("glove-print-analyzer-interface-number", ("number", state.AnalyzerId));
        AnalyzerNumberLabel.ToolTip = Loc.GetString("glove-print-analyzer-interface-number-tooltip",
            ("number", state.AnalyzerId));
        UpdatePrinterConnection();
        _printReadyAt = state.PrintReadyAt;
        _printCooldown = state.PrintCooldown;
        UpdateHistory(state.History);
        var pendingChanged = SelectedSampleId == null && previous != null && previous.PendingSwab != state.PendingSwab;
        RefreshResults(previousSelection != SelectedSampleId || pendingChanged);
    }

    private void UpdateHistory(List<GlovePrintAnalyzerHistoryEntry> history)
    {
        HistoryEntries.RemoveAllChildren();
        _historyButtons.Clear();
        HistoryEmpty.Visible = history.Count == 0;
        for (var i = history.Count - 1; i >= 0; i--)
        {
            var sample = history[i];
            var button = new Button
            {
                Text = GetSampleName(sample),
                ClipText = true,
                ToolTip = sample.Identifier,
                ToggleMode = true,
                HorizontalExpand = true,
            };
            button.OnPressed += _ => SelectSample(sample.Id);
            _historyButtons.Add(sample.Id, button);
            HistoryEntries.AddChild(button);
        }

        UpdateComparisonHistory(history);
    }

    private void SelectSample(int? id)
    {
        CompareHistory.Pressed = false;
        var changed = SelectedSampleId != id;
        SelectedSampleId = id;
        RefreshResults(changed);
    }

    private void RefreshResults(bool resetDescription = false)
    {
        TracesContainer.RemoveAllChildren();
        MicroFibersContainer.RemoveAllChildren();
        if (_results == null)
            return;

        var stored = SelectedSampleId == null
            ? null
            : _results.History.Find(sample => sample.Id == SelectedSampleId.Value);
        if (stored == null && SelectedSampleId != null)
        {
            SelectedSampleId = null;
            resetDescription = true;
        }

        PendingSamplePanel.Visible = _results.HasSwab;
        CurrentSample.Pressed = !CompareHistory.Pressed && SelectedSampleId == null;
        CurrentSample.ModulateSelfOverride = CurrentSample.Pressed
            ? Color.FromHex("#48AFCE")
            : Color.FromHex("#4296B2");
        foreach (var (id, button) in _historyButtons)
        {
            button.Pressed = !CompareHistory.Pressed && SelectedSampleId == id;
        }

        SelectedSampleLabel.Text = stored == null
            ? Loc.GetString("glove-print-analyzer-interface-current-sample")
            : GetSampleName(stored);
        SelectedSampleLabel.ToolTip = SelectedSampleLabel.Text;
        SelectedSampleLabel.Visible = !CompareHistory.Pressed && (stored != null || _results.HasSwab);
        var sourceName = stored?.SourceName ?? _results.PendingSourceName;
        SampleSourceLabel.Visible = !CompareHistory.Pressed && !string.IsNullOrEmpty(sourceName);
        SampleSourceLabel.Text = Loc.GetString("glove-print-analyzer-interface-source", ("source", sourceName));
        SampleSourceLabel.ToolTip = SampleSourceLabel.Text;
        _hasSample = stored != null;
        ResultsDetails.Visible = !CompareHistory.Pressed && stored != null;
        StatusLabel.Visible = !CompareHistory.Pressed && stored == null;
        NoTraces.Visible = stored != null && stored.GlovePrints.Count == 0;
        Analyze.Visible = !CompareHistory.Pressed && stored == null;
        Analyze.Disabled = stored != null || !_results.HasSwab || !_results.Used || _results.IsAnalyzing;
        UpdateDescription(stored?.Description ?? _results.PendingDescription, resetDescription);
        UpdatePrinterState();
        UpdateAnalysisProgress();
        UpdateComparisonView();

        if (stored != null)
        {
            StatusLabel.Text = string.Empty;
            DisplayTraces(stored.GlovePrints);
            DisplayMicroFibers(MicroFibersContainer, stored.MicroFibers,
                "glove-print-analyzer-interface-no-micro-fibers");
            return;
        }

        if (_results.IsAnalyzing)
        {
            StatusLabel.Text = Loc.GetString("glove-print-analyzer-interface-analyzing");
            return;
        }

        if (_analysisInterrupted)
        {
            StatusLabel.Text = Loc.GetString("glove-print-analyzer-interface-analysis-interrupted");
            return;
        }

        if (!_results.HasSwab)
        {
            StatusLabel.Text = Loc.GetString("glove-print-analyzer-interface-no-swab");
            return;
        }

        if (!_results.Used)
        {
            StatusLabel.Text = Loc.GetString("glove-print-analyzer-interface-unused-swab");
            return;
        }

        StatusLabel.Text = Loc.GetString("glove-print-analyzer-interface-ready");
    }

    private void UpdateDescription(string description, bool reset)
    {
        if (reset || !_descriptionLoaded || !_descriptionDirty || DescriptionEdit.Text == description)
        {
            DescriptionEdit.Text = description;
            _descriptionDirty = false;
        }

        _descriptionLoaded = true;
        _descriptionSource = description;
        UpdateDescriptionState();
    }

    private void UpdateDescriptionState()
    {
        var editable = !CompareHistory.Pressed && _results != null && SelectedSampleId != null;
        DescriptionEdit.Editable = editable;
        SaveDescription.Disabled = !editable || !_descriptionDirty;
    }

    private void DisplayTraces(List<GlovePrintTrace> traces)
    {
        foreach (var trace in traces)
        {
            TracesContainer.AddChild(CreateProfileRow(trace.Code, trace.Prototype,
                "glove-print-analyzer-interface-type", "glove-print-analyzer-interface-unknown-type"));
        }
    }

    private BoxContainer CreateProfileRow(string code, EntProtoId? prototypeId, string typeKey,
        string unknownTypeKey, string sourceName = "")
    {
        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            SeparationOverride = 8,
        };
        var itemName = string.IsNullOrEmpty(sourceName) ? Loc.GetString(unknownTypeKey) : sourceName;
        if (_prototype.TryIndex(prototypeId, out var prototype))
        {
            if (string.IsNullOrEmpty(sourceName))
                itemName = prototype.Name;

            var image = new EntityPrototypeView
            {
                MinSize = new Vector2(64, 64),
                MaxSize = new Vector2(64, 64),
                Stretch = SpriteView.StretchMode.Fill,
                VerticalAlignment = VAlignment.Center,
            };
            image.SetPrototype(prototype.ID);
            row.AddChild(image);
        }

        var text = new RichTextLabel { HorizontalExpand = true };
        text.SetMessage(FormattedMessage.FromUnformatted(Loc.GetString(typeKey, ("type", itemName)) + "\n" +
            Loc.GetString("glove-print-analyzer-interface-code", ("code", code))));
        row.AddChild(text);
        return row;
    }

    private void DisplayMicroFibers(BoxContainer container, List<MicroFiberTrace> microFibers, string emptyKey)
    {
        if (microFibers.Count == 0)
        {
            container.AddChild(new RichTextLabel
            {
                Text = Loc.GetString(emptyKey),
                HorizontalExpand = true,
            });
            return;
        }

        foreach (var fiber in microFibers)
        {
            container.AddChild(CreateProfileRow(fiber.Code, fiber.Prototype,
                "glove-print-analyzer-interface-item-type", "glove-print-analyzer-interface-unknown-item",
                fiber.SourceName));
        }
    }

    private string GetSampleName(GlovePrintAnalyzerHistoryEntry sample)
    {
        return Loc.GetString("glove-print-analyzer-interface-history-sample", ("identifier", sample.Identifier));
    }

    /// <summary>
    /// Prevents repeated clicks while the server processes a print request.
    /// </summary>
    public void StartPrintCooldown()
    {
        _printReadyAt = _timing.CurTime + _printCooldown;
        UpdatePrinterState();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        UpdatePrinterState();
        UpdateAnalysisProgress();
    }

    private void UpdatePrinterState()
    {
        if (_results == null)
        {
            Print.Disabled = true;
            return;
        }

        Print.Disabled = CompareHistory.Pressed || !_hasSample ||
            _results.PrinterStatus != GlovePrintAnalyzerPrinterStatus.Ready ||
            _timing.CurTime < _printReadyAt;
    }

    private void UpdatePrinterConnection()
    {
        var status = _results?.PrinterStatus ?? GlovePrintAnalyzerPrinterStatus.Disconnected;
        PrinterStatusIcon.ModulateSelfOverride = status == GlovePrintAnalyzerPrinterStatus.Disconnected
            ? Color.FromHex("#E66B6B")
            : Color.FromHex("#6ED18D");
        var tooltip = status switch
        {
            GlovePrintAnalyzerPrinterStatus.Ready => "glove-print-analyzer-interface-printer-ready",
            GlovePrintAnalyzerPrinterStatus.Unavailable => "glove-print-analyzer-interface-printer-unavailable",
            _ => "glove-print-analyzer-interface-printer-disconnected",
        };
        PrinterStatusIcon.ToolTip = Loc.GetString(tooltip);
    }

    private void UpdateAnalysisProgress()
    {
        AnalysisProgress.Visible = !CompareHistory.Pressed && SelectedSampleId == null &&
            _results != null && _results.IsAnalyzing;
        if (!AnalysisProgress.Visible || _results == null)
        {
            AnalysisProgress.Value = 0;
            return;
        }

        var duration = (_results.AnalysisFinishAt - _results.AnalysisStartedAt).TotalSeconds;
        if (duration <= 0)
        {
            AnalysisProgress.Value = 1;
            return;
        }

        var elapsed = (_timing.CurTime - _results.AnalysisStartedAt).TotalSeconds;
        AnalysisProgress.Value = (float)Math.Clamp(elapsed / duration, 0, 1);
    }
}
